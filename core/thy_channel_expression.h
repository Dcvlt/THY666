#ifndef THY_CHANNEL_EXPRESSION_H
#define THY_CHANNEL_EXPRESSION_H
#include "thy_core.h"

enum thy_channel_pressure_mode {
    THY_CHANNEL_PRESSURE_OFF=0, THY_CHANNEL_PRESSURE_POLY=1,
    THY_CHANNEL_PRESSURE_CHANNEL=2
};
enum thy_channel_bend_mode {
    THY_CHANNEL_BEND_OFF=0, THY_CHANNEL_BEND_UP=1, THY_CHANNEL_BEND_DOWN=2
};
#define THY_CHANNEL_EXPRESSION_ROUTES (THY_DEST_COUNT * 16u)

/* Ordinary MIDI channel expression, not MPE. Channel pressure is the maximum
 * of held, activated physical contributors on a destination/channel. Bend is
 * the newest held bend-enabled contributor there, falling back to the previous
 * held contributor or center when released. Sustain extends notes, not fingers:
 * these ordinary channel controls spring back even while notes are sustained.
 * Off disables a pad's contribution; it cannot isolate a note from channel-wide
 * expression generated by another pad. No dynamic allocation or hardware I/O.
 */
typedef struct thy_channel_expression {
    thy_core *core;
    uint8_t flags[THY_PAD_COUNT], pressure[THY_PAD_COUNT], bend_pressure[THY_PAD_COUNT];
    uint8_t rank[THY_PAD_COUNT];
    uint8_t excluded_destinations[THY_PAD_COUNT];
    uint8_t sent_pressure[THY_CHANNEL_EXPRESSION_ROUTES];
    uint16_t sent_bend[THY_CHANNEL_EXPRESSION_ROUTES];
    uint8_t used[THY_CHANNEL_EXPRESSION_ROUTES];
    uint8_t cursor[THY_DEST_COUNT];
} thy_channel_expression;

/* pressure | (bend << 2); invalid arguments produce UINT8_MAX. */
uint8_t thy_channel_expression_flags(uint8_t pressure, uint8_t bend);
int thy_channel_expression_flags_valid(uint8_t flags);
void thy_channel_expression_init(thy_channel_expression *,thy_core *);
/* Before EVERY nonempty ordinary physical/generated attack. Requested new
 * expression use initializes the receiver; other attacks still publish any
 * dirty channel cleanup before their Note On. A new bend-enabled physical pad
 * starts its newest binding at center. Generated callers pass flags=0.
 * This appends one atomic batch but deliberately leaves sent caches unchanged.
 * Caller can roll back core.queue_count if the subsequent core press fails.
 * For physical success, capture commits the prepared cache. Generated callers
 * use commit_prepared after their successful acquisition.
 */
int thy_channel_expression_prepare_attack(thy_channel_expression *,uint8_t channel,
    uint8_t destinations,uint8_t flags);
void thy_channel_expression_commit_prepared(thy_channel_expression *,uint8_t channel,
    uint8_t destinations,uint8_t flags);
/* Notify exactly once after a successful NEW physical attack, not an idempotent
 * re-press. Flags are immutable until release. Keys/routes stay in core owners;
 * only the activated prefix contributes expression, not future strum attacks.
 */
int thy_channel_expression_capture(thy_channel_expression *,uint8_t pad,uint8_t flags);
int thy_channel_expression_pressure(thy_channel_expression *,uint8_t pad,uint8_t value);
int thy_channel_expression_bend_pressure(thy_channel_expression *,uint8_t pad,uint8_t value);
/* Independent upper Aftertouch and lower primary-pressure axes. A single-stage
 * profile supplies the same value twice; two-stage profiles need not. */
int thy_channel_expression_pressure_axes(thy_channel_expression *,uint8_t pad,
    uint8_t aftertouch,uint8_t primary);
/* Notify after core release; this never queues and never rejects cleanup. */
void thy_channel_expression_release(thy_channel_expression *,uint8_t pad);
/* Called after core panic/cleanup too. Sent caches remain, so pending neutral
 * messages cannot be erased by panic. No controller messages are lost if the
 * core queue is full: latest desired state is recomputed on the next service.
 */
void thy_channel_expression_release_all(thy_channel_expression *);
/* USB session boundaries exclude already-held/pending USB contributions until
 * their physical release and a fresh capture. DIN ownership/expression remain
 * untouched. The transport separately neutralizes the new USB session. */
void thy_channel_expression_usb_reset(thy_channel_expression *);
/* Synchronize transport-suppressed pitches too: queue overrun and Note Ons
 * rejected during reconciliation need the same contributor exclusion. Bitmap
 * is two USB cables * 16 channels * 128 pitches, least-significant bit first.
 * Only ORs exclusions; fresh capture is the sole way to admit that pad again. */
void thy_channel_expression_usb_blocked(thy_channel_expression *,const uint8_t *bitmap,
    size_t bytes);
/* Foreground cadence is caller-owned (normally 8ms). At most FOUR messages per
 * destination per call. One destination/channel's D0/E0 update is atomic.
 * Legacy Poly remains caller-owned and is not emitted or max-merged here.
 */
int thy_channel_expression_service(thy_channel_expression *);

#endif
