"""Merge musical interval facts for the shared advisory engine.

Original pad layouts/slots remain in the lossless runtime projection. This
separate vocabulary collapses octave/voicing only for pitch-class comparison.
The supplementary vocabulary is plain JSON; no source code is evaluated.
The full merged audit remains local.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tools'))
from build_runtime_data import project_archive

# Existing advisory IDs remain stable, independently of playable catalog IDs.
BASE_SCALES = [('Major',0xab5),('Dorian',0x6ad),('Phrygian',0x5ab),
 ('Lydian',0xad5),('Mixolydian',0x6b5),('Natural minor',0x5ad),
 ('Locrian',0x56b),('Harmonic minor',0x9ad),('Melodic minor (ascending)',0xaad),
 ('Major pentatonic',0x295),('Minor pentatonic',0x4a9),('Blues',0x4e9),
 ('Whole tone',0x555),('Diminished (whole-half)',0xb6d),
 ('Diminished (half-whole)',0x6db),('Chromatic',0xfff)]
BASE_CHORDS = [0x091,0x089,0x049,0x111,0x085,0x0a1,0x891,0x489,0x491,0x449,0x249]
ROOTS = dict(C=0,D=2,E=4,F=5,G=7,A=9,B=11)

def steps_mask(steps):
    if not isinstance(steps, (list,tuple)) or not steps or any(type(n) is not int or not 0<=n<12 for n in steps):
        raise ValueError('Invalid scale/chord intervals')
    if len(set(steps))!=len(steps) or 0 not in steps:
        raise ValueError('Intervals must be unique and include the root')
    return sum(1<<n for n in steps)

def read_collection(path):
    data=json.loads(path.read_text())
    if data.get('format')!='thy666.interval-collection' or data.get('version')!=1:
        raise ValueError('Unsupported interval collection')
    scales=[];chords=[]
    for row in data['scales']:
        if not isinstance(row['name'],str) or not row['name'].strip():
            raise ValueError('Invalid scale name')
        scales.append((row['name'],steps_mask(row['intervals'])))
    for row in data['chords']:
        if not isinstance(row['names'],list) or not row['names'] or any(not isinstance(n,str) for n in row['names']):
            raise ValueError('Invalid chord aliases')
        chords.append((row['names'],steps_mask(row['intervals'])))
    return scales,chords

def merge(projection, extra_scales, extra_chords):
    scales=[{'name':name,'mask':mask,'aliases':[]} for name,mask in BASE_SCALES]
    by_mask={v['mask']:v for v in scales}
    def scale(name,mask):
        if not mask&1 or mask>4095: raise ValueError('Invalid root-relative scale')
        if mask not in by_mask:
            entry={'name':name,'mask':mask,'aliases':[]};scales.append(entry);by_mask[mask]=entry
        elif name!=by_mask[mask]['name'] and name not in by_mask[mask]['aliases']:
            by_mask[mask]['aliases'].append(name)
    records=projection['pad_records']
    for group in projection['groups']:
        variant=next(s for s in projection['scales'] if s['group_index']==group['index'] and s['root_label']=='C')
        notes={n['midi']%12 for ref in variant['pads'][48:] if ref is not None for n in records[ref[1]]['notes']}
        scale(group['name'],steps_mask(sorted(notes)))
    for name,mask in extra_scales: scale(name,mask)
    chords=list(BASE_CHORDS); aliases={}; rootless=[]
    def chord(mask,names):
        if mask not in chords: chords.append(mask)
        aliases.setdefault(str(mask),[])
        for name in names:
            if name not in aliases[str(mask)]: aliases[str(mask)].append(name)
    # Only chord-side records; musical MIDI slots, not potentially inaccurate
    # quality suffixes, determine the set. Keep rootless cases in the audit.
    chord_indices={ref[1] for s in projection['scales'] for ref in s['pads'][:48] if ref is not None}
    for index in sorted(chord_indices):
        record=records[index]
        if not record['notes']: continue
        found=re.match(r'^([A-G])([#b]?)(.*)$',record['name'])
        if not found: raise ValueError('Chord record has no parseable root: '+record['name'])
        root=(ROOTS[found[1]]+{'':0,'#':1,'b':-1}[found[2]])%12
        mask=0
        for n in record['notes']: mask|=1<<((n['midi']-root)%12)
        if not mask&1: rootless.append(index);continue
        chord(mask,[found[3]])
    for names,mask in extra_chords: chord(mask,names)
    if len(scales)>255: raise ValueError('Advisory family identity exceeds uint8_t')
    return {'format':'thy666.harmonic-vocabulary','version':1,'scales':scales,
            'chord_masks':chords,'chord_aliases':aliases,'rootless_record_indices':rootless,
            'original_projection':projection}

def header(model):
    lines=['/* Generated by tools/merge_harmony_catalog.py. Musical interval facts only. */',
           '/* Existing 16 advisory IDs and original playable catalog IDs stay unchanged. */',
           'static const struct {const char *name;uint16_t mask;} guidance_scales[]={']
    for row in model['scales']:
        lines.append('    {'+json.dumps(row['name'],ensure_ascii=True)+f",0x{row['mask']:03x}u"+'},')
    lines+=['};','static const uint16_t guidance_chords[]={',
            '    '+','.join(f'0x{m:03x}u' for m in model['chord_masks']),'};',
            '_Static_assert(sizeof guidance_scales/sizeof guidance_scales[0]<=255u,"advisory family IDs");','']
    return '\n'.join(lines)

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--archive',type=Path,required=True)
    parser.add_argument('--intervals',type=Path,default=ROOT/'core/harmony-intervals.json')
    parser.add_argument('--output',type=Path,default=ROOT/'build/harmony-catalog/merged.json')
    parser.add_argument('--header',type=Path,default=ROOT/'core/thy_harmony_catalog.h')
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    raw=args.archive.read_bytes()
    projection=project_archive(json.loads(raw),archive_sha256=hashlib.sha256(raw).hexdigest(),archive_size_bytes=len(raw))
    model=merge(projection,*read_collection(args.intervals))
    generated=header(model)
    if args.check:
        if args.header.read_text()!=generated: raise SystemExit('Harmonic catalog is stale')
    else:
        if not args.output.resolve().is_relative_to((ROOT/'build').resolve()):
            raise ValueError('Full merged data must stay under ignored build/')
        args.output.parent.mkdir(parents=True,exist_ok=True)
        args.output.write_text(json.dumps(model,separators=(',',':'))+'\n')
        args.header.write_text(generated)
    print(json.dumps({'scale_families':len(model['scales']),'chord_sets':len(model['chord_masks']),
       'original_layouts':len(projection['scales']),'original_records':len(projection['pad_records']),
       'rootless_records_preserved_without_advisory_root':len(model['rootless_record_indices'])}))
if __name__=='__main__': main()
